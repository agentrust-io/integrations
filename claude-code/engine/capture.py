# baseline integrity
# --------------------------------------------------------------------------- #
# Sealing and state now live in the core. See its seal module for why this is a
# bare digest rather than an HMAC, and what the digest does and does not defend
# against. The names below stay module-level because the hook, the report and the
# tests refer to them here.
_INTEGRITY_FIELD = core.SEAL_FIELD

INTEGRITY_OK = core.INTEGRITY_OK
INTEGRITY_UNSEALED = core.INTEGRITY_UNSEALED
INTEGRITY_BROKEN = core.INTEGRITY_BROKEN

#: Retained so an older caller keeps working; UNSEALED is the current name.
INTEGRITY_UNTAGGED = INTEGRITY_UNSEALED

state_digest = core.state_digest
attach_integrity = core.attach_seal
check_integrity = core.check_seal


# --------------------------------------------------------------------------- #
# state helpers
# --------------------------------------------------------------------------- #
#: Atomic, so a crash mid-write cannot leave a truncated baseline that reads as
#: corrupt on every future session. The previous implementation wrote in place.
_save = core.save_state
_load = core.load_state


def _save_baseline(snap: dict) -> dict:
    """Seal and write the approved baseline. Returns what was written."""
    return core.save_baseline(BASELINE, snap)


def _live_from(args) -> dict | None:
    """Load the live-context file, or exit with a clear message.

    The file is written by the agent, so a missing path or malformed JSON is a
    realistic failure. Reporting it plainly beats a traceback, and silently
    treating it as absent would be worse than both: the run would proceed with
    model, tools, and MCP unmeasured while the caller believed it had supplied
    them, which is exactly the false-assurance this tool exists to prevent.
    """
    if not args.live_context:
        return None
    path = Path(args.live_context)
    try:
        loaded = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise SystemExit(f"live-context file could not be read: {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise SystemExit(f"live-context file is not valid JSON: {path}: {exc}") from exc
    if not isinstance(loaded, dict):
        raise SystemExit(
            f"live-context file must contain a JSON object, got "
            f"{type(loaded).__name__}: {path}"
        )
    return loaded


# --------------------------------------------------------------------------- #
# subcommands
# --------------------------------------------------------------------------- #
def cmd_snapshot(args) -> int:
    snap = snapshot(_live_from(args))
    _save(LATEST, snap)
    print(json.dumps(snap, indent=2) if args.json else render_report(snap, None, False))
    return 0


def _emit_context(msg: str) -> None:
    out = {"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": msg}}
    print(json.dumps(out))


def _hook_body() -> None:
    try:
        payload = json.load(sys.stdin) if not sys.stdin.isatty() else {}
    except (json.JSONDecodeError, ValueError):
        payload = {}
    if not isinstance(payload, dict):
        payload = {}
    live = {k: payload[k] for k in ("model_id", "model_provider", "model_version") if k in payload}
    snap = snapshot(live or None)
    _save(LATEST, snap)

    base = _load(BASELINE)
    if base is None:
        _save_baseline(snap)
        msg = ("AgenTrust: baseline established for this Claude agent "
               f"({len(snap['skills'])} skills, {len(snap['mcp_servers'])} MCP on disk). "
               "Future sessions are checked against it. Run /manifest approve to re-baseline.")
    elif check_integrity(base) == INTEGRITY_BROKEN:
        # Report this ahead of any drift. If the baseline was altered, the
        # comparison against it means nothing, so a "no changes" result would be
        # worse than no result at all.
        msg = ("AgenTrust WARNING: your approved baseline failed its integrity "
               "check. baseline.json was modified outside this tool, so any drift "
               "comparison against it is unreliable. Run /manifest verify, and "
               "re-approve only once you are satisfied the current setup is what "
               "you intend.")
    else:
        changes = diff(base, snap)
        if not changes:
            msg = "AgenTrust: agent composition unchanged since your approved baseline (nothing added, nothing subtracted)."
        else:
            detail = "; ".join(f"{c['change']} {c['what']} {c['detail']}" for c in changes[:8])
            msg = (f"AgenTrust WARNING: {len(changes)} change(s) to your agent since baseline: "
                   f"{detail}. Run /manifest verify for detail, or /manifest approve to accept.")
    _emit_context(msg)


def cmd_hook(args) -> int:
    """SessionStart entrypoint. Reads the hook payload on stdin, snapshots,
    checks drift against the baseline, and emits SessionStart context.

    A SessionStart hook must never block or break the session. Whatever goes
    wrong (unreadable config, a bug, an OS error), emit a benign context and
    exit 0 rather than dumping a traceback into the user's session.
    """
    try:
        _hook_body()
    except Exception:  # noqa: BLE001 -- last-resort guard: the session must start
        _emit_context(
            "AgenTrust: integrity check skipped this session (could not read the "
            "agent configuration). Run /manifest verify to check manually."
        )
    return 0


def cmd_verify(args) -> int:
    base = _load(BASELINE)
    # Always re-snapshot so verify reflects the agent's CURRENT composition,
    # not a cached session-latest.json. Otherwise drift introduced after
    # session start (a skill dropped in, a widened permission) would be missed
    # and verify would falsely report "nothing added, nothing subtracted".
    # The live context supplied by the /manifest command is merged in here.
    snap = snapshot(_live_from(args))
    _save(LATEST, snap)
    if base is None:
        print("No approved baseline yet. Run /manifest approve to establish one.")
        return 0
    integrity = check_integrity(base)
    print(render_report(snap, diff(base, snap), False, integrity=integrity,
                        baseline_digest=state_digest(base)))
    return 0


def cmd_approve(args) -> int:
    snap = snapshot(_live_from(args))
    _save(LATEST, snap)
    tagged = _save_baseline(snap)
    digest = tagged[_INTEGRITY_FIELD]["digest"]
    print(render_report(snap, [], False, integrity=INTEGRITY_OK, baseline_digest=digest))
    print(f"\nApproved baseline updated: {BASELINE}")
    # The digest sits beside the content it describes, so on its own it catches
    # accidents rather than adversaries. Recorded off this machine, it is what
    # makes a silent re-baseline visible to a human.
    print(f"Baseline digest: {digest}")
    print("Record that digest somewhere off this machine. `verify` prints the")
    print("digest of the baseline it read, so a mismatch tells you the baseline")
    print("was replaced even by someone who could recompute the digest locally.")
    if args.sign:
        _, _ = sign_all(snap, Path(args.out))
        print(f"Signed manifest + trace written to {args.out}")
    return 0


def cmd_report(args) -> int:
    snap = snapshot(_live_from(args))
    _save(LATEST, snap)
    base = _load(BASELINE)
    changes = diff(base, snap) if base else None
    sign_all(snap, Path(args.out))
    print(render_report(snap, changes, True))
    print(f"\nwrote {args.out}/manifest.json  {args.out}/trace.json")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="agentrust-capture", description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("snapshot", "hook", "verify", "approve", "report"):
        p = sub.add_parser(name)
        p.add_argument("--live-context", help="JSON of live session facts (model, tools, mcp)")
        p.add_argument("--out", default=".", help="output dir for signed records")
        p.add_argument("--json", action="store_true", help="emit raw JSON snapshot")
        p.add_argument("--sign", action="store_true", help="(approve) also write signed records")
    args = ap.parse_args(argv)
    return {
        "snapshot": cmd_snapshot, "hook": cmd_hook, "verify": cmd_verify,
        "approve": cmd_approve, "report": cmd_report,
    }[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
