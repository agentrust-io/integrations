"""AgenTrust capture engine for Claude Code.

Introspects the running Claude Code agent and produces, for one session:

  * an Agent Manifest -- what the agent IS: skills, tools, MCP servers, model,
    permission policy, and instruction layer, each fingerprinted. Signed with
    agent-manifest (Ed25519).
  * a TRACE Trust Record -- what the agent DID this run. Signed with
    agentrust-trace. Shares the manifest's agent_id and policy hash.
  * a plain-English integrity report.

The design keeps the SessionStart hook cheap and dependency-free: `snapshot`,
`verify`, and `approve` use only the Python standard library. Signing (which
needs agent-manifest / agentrust-trace) runs only in `report` and `approve
--sign`, on demand.

The core question it answers: "is the agent I am running the one I approved --
nothing added, nothing subtracted?"

Safety: hashes files, never stores secrets. Never reads .credentials.json.
Records skill / MCP / tool NAMES only, never tokens or environment values.

Subcommands:
  snapshot   capture the agent's composition from disk (stdlib only)
  hook       SessionStart entrypoint: snapshot + drift check + warn
  verify     diff the latest snapshot against the approved baseline
  approve    promote the latest snapshot to the approved baseline
  report     build + sign the manifest and TRACE record, render the report
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import stat
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

# Prefer the installed package; fall back to the pinned vendored copy. The
# SessionStart hook runs before anything is installed, so the fallback is what
# makes drift detection work on a bare plugin install. The copy is generated by
# scripts/sync_vendored_core.py and CI fails if it disagrees with the package.
try:
    import agentrust_capture_core as core
except ImportError:  # pragma: no cover - exercised by the bare-install path
    sys.path.insert(0, str(Path(__file__).resolve().parent / "_vendor"))
    import agentrust_capture_core as core

#: Version of WHAT this engine measures, distinct from what it found.
#:
#: Bump it whenever a change makes a fingerprint incomparable to one written by
#: an earlier version, so an upgrade cannot be mistaken for drift. A baseline at
#: an older scope is reported as needing a one-time re-approve instead of showing
#: every affected category as changed: an alarm the user knows is false is worse
#: than no alarm, because it teaches them to dismiss the next one.
#:
#: 1  skills fingerprinted by SKILL.md alone; instruction layer as a single hash
#: 2  skills fingerprinted across their whole directory; per-file instruction
#:    hashes added alongside the rollup
MEASUREMENT_SCOPE = 2

CLAUDE_HOME = Path(os.path.expanduser("~")) / ".claude"
STATE_DIR = CLAUDE_HOME / "agentrust"
BASELINE = STATE_DIR / "baseline.json"
LATEST = STATE_DIR / "session-latest.json"
SIGNING_KEY = STATE_DIR / "signing_key.json"


# --------------------------------------------------------------------------- #
# hashing (files only, never secrets)
# --------------------------------------------------------------------------- #
_sha_bytes = core.sha_bytes
_sha_file = core.sha_file
_uuid7 = core.uuid7
_now_iso = core.now_iso


def _sha_tree(root: Path, pattern: str = "*.md") -> str:
    """Rollup digest over an instruction tree.

    Kept local rather than replaced by core.tree_digest: this returns the digest of
    the empty string for a missing tree, where the core returns None to distinguish
    "no component here" from "a component with no files". Changing that would move
    the system_prompt fingerprint for every existing baseline, so the rollup keeps
    its own semantics and the core is used where a component is being measured.
    """
    if not root.exists():
        return _sha_bytes(b"")
    return core.tree_digest(root, pattern=pattern, exclude_dirs=frozenset(),
                            exclude_suffixes=frozenset()) or _sha_bytes(b"")


# --------------------------------------------------------------------------- #
# snapshot: read the real box (stdlib only)
# --------------------------------------------------------------------------- #
#: Re-exported from the core, which owns the denylist so that a hostile skill
#: cannot exempt its own payload by shipping an ignore file. Kept as module-level
#: names because the hook, the report and the tests refer to them here.
SKILL_EXCLUDE_DIRS = core.EXCLUDE_DIRS
SKILL_EXCLUDE_SUFFIXES = core.EXCLUDE_SUFFIXES

#: Digest every behavioural file in one skill directory, or None when the
#: directory yielded nothing readable. See core.tree_digest for why the whole tree
#: is covered rather than SKILL.md alone.
_skill_fingerprint = core.tree_digest


def _skills() -> dict[str, str]:
    out: dict[str, str] = {}
    sdir = CLAUDE_HOME / "skills"
    # is_dir(), not exists(): tolerate ~/.claude/skills being a stray file.
    if not sdir.is_dir():
        return out
    try:
        entries = sorted(sdir.iterdir())
    except OSError:
        return out
    for d in entries:
        try:
            # SKILL.md is what makes a directory a skill; without it the
            # directory is not loaded as one and is not measured as one.
            if not (d / "SKILL.md").is_file():
                continue
        except OSError:
            continue  # unreadable skill file: skip it, never crash the hook
        fp = _skill_fingerprint(d)
        if fp is not None:
            out[d.name] = fp
    return out


def _instruction_files(pattern: str = "*.md") -> dict[str, str]:
    """Hash each instruction file separately, keyed by path relative to the tree.

    The rollup in ``hashes.system_prompt`` says only that something in the
    instruction layer moved. Across a real memory directory that is one bit of
    signal over dozens of files, which leaves a reader unable to act on the
    warning. Per-file digests let a diff name the file that changed.

    Scoped to ``*.md`` deliberately: this tree also holds session transcripts and
    other machine-written state that changes constantly, and folding those in
    would make the instruction layer permanently dirty.
    """
    out: dict[str, str] = {}
    root = CLAUDE_HOME / "projects"
    if not root.is_dir():
        return out
    try:
        paths = sorted(p for p in root.rglob(pattern) if p.is_file())
    except OSError:
        return out
    for f in paths:
        try:
            out[f.relative_to(root).as_posix()] = _sha_file(f)
        except (OSError, ValueError):
            continue  # unreadable file: skip it, never crash the hook
    return out


def _server_names(mapping: object) -> list[str]:
    """Keys of a config mapping, or [] if it is not a dict (malformed config)."""
    return list(mapping.keys()) if isinstance(mapping, dict) else []


def _policy() -> tuple[str, list[str]]:
    settings = CLAUDE_HOME / "settings.json"
    if not settings.is_file():
        return _sha_bytes(b"{}"), []
    # Always hash the real file bytes so a hand-edit is detected as drift, even
    # if the JSON is malformed. Parsing the allow-list is best-effort: bad JSON
    # or an unexpected shape yields an empty list rather than crashing the hook.
    try:
        policy_hash = _sha_file(settings)
    except OSError:
        return _sha_bytes(b"{}"), []
    allow: list[str] = []
    try:
        data = json.loads(settings.read_text(encoding="utf-8"))
        if isinstance(data, dict):
            perms = data.get("permissions")
            if isinstance(perms, dict) and isinstance(perms.get("allow"), list):
                allow = perms["allow"]
    except (json.JSONDecodeError, OSError):
        pass
    return policy_hash, allow


def _mcp_from_config() -> list[str]:
    """MCP server names declared on disk (global + per-project). Names only.

    Best-effort: a missing, unreadable, malformed, or unexpectedly-shaped
    ``~/.claude.json`` yields an empty list, never an exception.
    """
    servers: set[str] = set()
    cfg = Path(os.path.expanduser("~")) / ".claude.json"
    if not cfg.is_file():
        return []
    try:
        data = json.loads(cfg.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    if not isinstance(data, dict):
        return []
    servers.update(_server_names(data.get("mcpServers")))
    projects = data.get("projects")
    if isinstance(projects, dict):
        for proj in projects.values():
            if isinstance(proj, dict):
                servers.update(_server_names(proj.get("mcpServers")))
    return sorted(servers)


def _identity() -> str:
    host = os.environ.get("COMPUTERNAME") or os.environ.get("HOSTNAME") or "localhost"
    user = os.environ.get("USERNAME") or os.environ.get("USER") or "user"
    return f"spiffe://claude-code.local/{user}/{host}".lower()


def snapshot(live: dict | None = None) -> dict:
    """Capture the agent's composition. `live` carries session facts the agent
    knows at runtime (model, tool roster, connected MCP servers) that a shell
    hook cannot see; merged in when present."""
    live = live or {}
    skills = _skills()
    policy_hash, allow = _policy()
    prompt_hash = _sha_tree(CLAUDE_HOME / "projects")  # instruction / memory layer

    # Skills, permissions, and the instruction layer are observable from disk in
    # any context (including the shell hook). The live tool roster and connected
    # MCP servers are runtime state only the agent can report; they are recorded
    # -- and diffed -- only when a live context supplies them. `observed` marks
    # which categories this snapshot actually measured, so a disk-only hook
    # snapshot is never diffed against the live categories of a richer baseline.
    observed = ["skills", "policy", "prompt", "instructions"]
    mcp_live = live.get("mcp_servers")
    mcp = mcp_live if mcp_live is not None else _mcp_from_config()
    builtin = live.get("builtin_tools") or []
    tools = sorted(builtin) + [f"mcp:{s}" for s in sorted(mcp)]
    if mcp_live is not None:
        observed.append("mcp")
    if builtin:
        observed.append("tools")

    return {
        "captured_at": _now_iso(),
        "scope": MEASUREMENT_SCOPE,
        "observed": observed,
        "agent_id": _identity(),
        "model": {
            "provider": live.get("model_provider", "anthropic"),
            "model_id": live.get("model_id", "unknown"),
            "version": live.get("model_version", "unknown"),
            "capability_level": live.get("capability_level"),
        },
        "skills": skills,
        "instruction_files": _instruction_files(),
        "policy_hash": policy_hash,
        "allow_rules": allow,
        "prompt_hash": prompt_hash,
        "mcp_servers": mcp,
        "tools": tools,
        "data_class": live.get("data_class", "internal"),
        "hashes": {
            "system_prompt": prompt_hash,
            "policy_bundle": policy_hash,
            "skills_set": _sha_bytes(json.dumps(skills, sort_keys=True).encode()),
            "tool_catalog": _sha_bytes(json.dumps(tools, sort_keys=True).encode()),
        },
    }


# --------------------------------------------------------------------------- #
# diff: nothing added, nothing subtracted
# --------------------------------------------------------------------------- #
def _instruction_file_changes(base: dict, cur: dict) -> list[dict]:
    """Per-file additions, removals and edits in the instruction layer."""
    b_f, c_f = base.get("instruction_files", {}), cur.get("instruction_files", {})
    if not b_f and not c_f:
        return []
    out: list[dict] = []
    for name in sorted(set(c_f) - set(b_f)):
        out.append({"change": "added", "what": "instruction file", "detail": name})
    for name in sorted(set(b_f) - set(c_f)):
        out.append({"change": "removed", "what": "instruction file", "detail": name})
    for name in sorted(set(b_f) & set(c_f)):
        if b_f[name] != c_f[name]:
            out.append({"change": "changed", "what": "instruction file", "detail": name})
    return out


def diff(base: dict, cur: dict) -> list[dict]:
    """Return a list of {change, what, detail}, change in {added,removed,changed}.

    Only categories BOTH snapshots observed are compared, so a disk-only hook
    snapshot never reports the live tool roster of a richer baseline as removed.

    Categories whose fingerprints became incomparable because the engine widened
    what it measures are reported once as a scope change needing re-approval,
    rather than as drift that never happened.
    """
    out: list[dict] = []
    obs = set(base.get("observed", ["skills", "policy", "prompt"])) & set(
        cur.get("observed", ["skills", "policy", "prompt"])
    )

    # A baseline written before MEASUREMENT_SCOPE 2 holds skill fingerprints over
    # SKILL.md alone, so comparing them against whole-directory digests would
    # report every skill as changed. Drop skills from the comparison and say why.
    base_scope = base.get("scope", 1)
    if base_scope != MEASUREMENT_SCOPE:
        out.append({
            "change": "changed",
            "what": "measurement scope",
            "detail": (
                f"widened from {base_scope} to {MEASUREMENT_SCOPE}; skill "
                "fingerprints now cover the whole skill directory. Re-approve "
                "once to compare on the new scope."
            ),
        })
        obs.discard("skills")

    if "prompt" in obs and base["hashes"].get("system_prompt") != cur["hashes"].get("system_prompt"):
        # Name the files when both snapshots carry per-file digests. The rollup
        # only says the layer moved, which over dozens of files gives a reader
        # nothing to act on. Fall back to the rollup against a scope-1 baseline
        # that has no per-file detail to compare against.
        per_file = _instruction_file_changes(base, cur) if "instructions" in obs else []
        out.extend(per_file or
                   [{"change": "changed", "what": "instruction layer", "detail": "system_prompt"}])
    if "policy" in obs and base["hashes"].get("policy_bundle") != cur["hashes"].get("policy_bundle"):
        out.append({"change": "changed", "what": "permissions", "detail": "policy_bundle"})

    if "skills" in obs:
        b_sk, c_sk = base.get("skills", {}), cur.get("skills", {})
        for name in sorted(set(c_sk) - set(b_sk)):
            out.append({"change": "added", "what": "skill", "detail": name})
        for name in sorted(set(b_sk) - set(c_sk)):
            out.append({"change": "removed", "what": "skill", "detail": name})
        for name in sorted(set(b_sk) & set(c_sk)):
            if b_sk[name] != c_sk[name]:
                out.append({"change": "changed", "what": "skill", "detail": name})

    if "mcp" in obs:
        b_mcp, c_mcp = set(base.get("mcp_servers", [])), set(cur.get("mcp_servers", []))
        for s in sorted(c_mcp - b_mcp):
            out.append({"change": "added", "what": "MCP server", "detail": s})
        for s in sorted(b_mcp - c_mcp):
            out.append({"change": "removed", "what": "MCP server", "detail": s})

    if "tools" in obs:
        b_t, c_t = set(base.get("tools", [])), set(cur.get("tools", []))
        for t in sorted(c_t - b_t):
            out.append({"change": "added", "what": "tool", "detail": t})
        for t in sorted(b_t - c_t):
            out.append({"change": "removed", "what": "tool", "detail": t})
    return out


