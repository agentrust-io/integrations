def test_legacy_action_ref_digest_cannot_satisfy_the_v2_binding() -> None:
    # compute_action_ref is a pre-draft compatibility digest over a different,
    # camelCase preimage. It is deliberately still shipped. It is not an
    # action_ref and must never bind one.
    action = _action()
    legacy = compute_action_ref(
        agent_id=action["agent_id"],
        action_type=action["action_type"],
        scope_required=action["scope_required"],
        timestamp=action["issued_at"],
    )
    assert legacy != compute_action_ref_v2(action)
    # Minted carrying the legacy digest from the start, not mutated afterwards,
    # so the identifier and the signature stay correct and the binding is the
    # only thing that fails.
    receipt, pinned, _ = _mint(action=action, action_ref=legacy)
    result = _verify(receipt, pinned, action)
    assert result["status"] == INVALID
    assert result["checks"]["receipt_id"] == PASS
    assert result["checks"]["signature"] == PASS
    assert result["checks"]["stage"] == PASS
    assert result["checks"]["action_binding"] == FAIL
    assert result["reasons"] == ["action_ref_mismatch"]


