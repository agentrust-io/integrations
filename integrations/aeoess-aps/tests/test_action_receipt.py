def test_committed_delegation_verifies_on_its_own_and_the_receipt_does_not_establish_it() -> None:
    delegation = _fixture("delegation.json")
    keys = _fixture("keys.json")["delegation_verification_key"]
    chain = verify_authority_delegation_chain(
        [delegation],
        now="2026-09-18T12:00:00.000Z",
        resolve_verification_key=lambda *_args: keys[delegation["verification_method"]],
        trust_root=lambda _root: True,
        resolve_revocation=lambda _delegation: "active",
    )
    assert chain.state == "valid"
    # That result came from verify_authority_delegation_chain, not from the
    # receipt verifier. The receipt verifier only compares delegation_ref to
    # the caller's expectation, so it reports delegation_ref as checked while
    # establishing nothing about the delegation itself.
    meta = _fixture("meta.json")
    result = verify_aps_action_receipt(
        _fixture("receipt.json"),
        resolve_key=_resolver(_fixture("keys.json")["pinned"]),
        reference_time=datetime.fromisoformat(meta["reference_time"].replace("Z", "+00:00")),
        max_age_seconds=meta["max_age_seconds"],
        expected_delegation_ref=delegation["delegation_id"],
    )
    assert result["checks"]["delegation_ref"] == PASS
    assert result["reasons"] == []


def test_the_delegation_check_is_string_equality_and_nothing_more() -> None:
    # The boundary made visible: a receipt naming a delegation that does not
    # exist anywhere still passes the delegation_ref check, because the check
    # is a comparison against what the caller said to expect. Establishing that
    # the delegation is real, current and unrevoked is
    # verify_authority_delegation_chain's job and happens elsewhere.
    invented = "sha256:" + "9" * 64
    receipt, pinned, action = _mint(delegation_ref=invented)
    result = _verify(receipt, pinned, action, expected_delegation_ref=invented)
    assert result["status"] == VERIFIED
    assert result["checks"]["delegation_ref"] == PASS


