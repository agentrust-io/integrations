# Key resolution. Every outcome where no signature was checked is a non
# verification. Only a checked signature that did not verify is a failure.


@pytest.mark.parametrize(
    "resolved,reason",
    [
        (None, "key_unresolved"),
        ({"outcome": "not_found"}, "key_not_found"),
        ({"outcome": "ambiguous"}, "key_ambiguous"),
        ({"outcome": "malformed"}, "key_material_malformed"),
        ({"outcome": "unreachable"}, "key_unreachable"),
        ("zz", "key_material_malformed"),
    ],
)
def test_resolution_outcomes_are_unverified_and_never_a_failed_signature(resolved, reason) -> None:
    receipt, _pinned, action = _mint()
    result = _verify(receipt, {}, action, resolve_key=lambda *_args: resolved)
    assert result["status"] == UNVERIFIED
    assert result["checks"]["signature"] == NOT_CHECKED
    assert result["reasons"] == [f"signature:{AGENT}:{KEY_ID}:{reason}"]


def test_unsupported_key_scheme_is_unverified_and_keeps_the_core_status() -> None:
    # The one place an APS `unsupported` state translates to a TRACE side
    # non verification. The scheme was not verified and is not pretended to be.
    receipt, _pinned, action = _mint()
