"""APS action intent receipt as external action evidence: verifier tests.

Two sources of receipts:

- the committed fixture in ``fixtures/action-receipt/``, regenerated byte for
  byte by ``generate.py`` from published seeds, verified at the fixed
  ``reference_time`` in ``meta.json`` so the result is the same on every run.
- receipts minted in-process with ephemeral keys for the negative cases.

Every negative case changes exactly one thing and asserts both the status and
the check that carried it, so a refusal is attributed rather than assumed.

Stage negatives are minted, never mutated. ``create_receipt_v1`` deliberately
does not enforce the draft section 5.3 rules, so a stage-invalid record can be
built with a correct ``receipt_id`` and a valid signature. Mutating a signed
receipt instead would break the identifier and the signature as well, and the
test would no longer isolate the stage rule it claims to cover.
"""
from __future__ import annotations

import copy
import hashlib
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest
from agent_passport import (
    compute_action_ref,
    compute_action_ref_v2,
    compute_payload_ref_v1,
    create_action_reference_input_v2,
    verify_authority_delegation_chain,
)
from agent_passport.crypto import generate_key_pair
from agent_passport.receipt_core import create_receipt_v1

from aps_action_receipt import (
    ACTION_INTENT_RECEIPT_TYPE,
    CHECKS,
    FAIL,
    INVALID,
    NOT_CHECKED,
    PASS,
    STATUSES,
    UNVERIFIED,
    VERIFIED,
    verify_aps_action_receipt,
)

FIXTURE_DIR = Path(__file__).resolve().parent.parent / "fixtures" / "action-receipt"
FIXTURE_RECEIPT_SHA256 = "cbbea5a88ff06729f8bfeac0a6878b1a640231709ce3846eae58f5af435dcd60"

AGENT = "did:aps:test:agent"
KEY_ID = "k1"
#: An AuthorityDelegationV1 identifier, which carries its own ``sha256:``
#: prefix. A bare digest here is refused by the envelope validator, which one
#: of the regression tests below pins.
DELEGATION_REF = "sha256:" + hashlib.sha256(b"test-delegation").hexdigest()
ISSUED_AT = datetime(2026, 9, 18, 12, 0, 0, tzinfo=timezone.utc)
REFERENCE = ISSUED_AT + timedelta(minutes=5)
MAX_AGE = 600
INTENT_RESULT = {"profile": "aps-action-intent-result-v1", "status": "declared"}


def _iso_ms(value: datetime) -> str:
    return value.strftime("%Y-%m-%dT%H:%M:%S.") + f"{value.microsecond // 1000:03d}Z"


def _action(agent: str = AGENT, **overrides) -> dict:
    """The exact aps-action-ref-v2 input object, built by the SDK."""
    fields = {
        "agent_id": agent,
        "action_type": "calendar.event.create",
        "target": "https://calendar.example.com/calendars/primary",
        "payload_ref": compute_payload_ref_v1({"title": "test"}),
        "scope_required": ["calendar:write"],
        "issued_at": "2026-09-18T11:59:58.000Z",
        "nonce": "0" * 32,
    }
    fields.update(overrides)
    return create_action_reference_input_v2(**fields)


def _mint(
    *,
    issued_at: datetime = ISSUED_AT,
    action: dict | None = None,
    receipt_type: str = ACTION_INTENT_RECEIPT_TYPE,
    subject_agent: str = AGENT,
    issuer: str | None = None,
    action_ref: str | None = None,
    result: dict | None = None,
    delegation_ref: str = DELEGATION_REF,
    extra: dict | None = None,
) -> tuple[dict, dict, dict]:
    """Return (receipt, pinned keys, action preimage) with an ephemeral issuer key.

    Defaults mint a draft section 5.3.1 conformant action intent: the issuer is
    the acting agent and signs, and the result is the exact declaration object.
    Every argument exists so a single one of those properties can be broken
    while the envelope, the identifier and the signature stay correct.
    """
    action = _action() if action is None else action
    issuer = subject_agent if issuer is None else issuer
    keys = generate_key_pair()
    fields = {
        "profile": "aps-receipt-v1",
        "receipt_type": receipt_type,
        "issuer": issuer,
        "subject_agent": subject_agent,
        "action_ref": compute_action_ref_v2(action) if action_ref is None else action_ref,
        "delegation_ref": delegation_ref,
        "issued_at": _iso_ms(issued_at),
        "evidence_refs": [],
        "result": INTENT_RESULT if result is None else result,
    }
    fields.update(extra or {})
    receipt = create_receipt_v1(
        fields, [{"signer": issuer, "key_id": KEY_ID, "private_key": keys["privateKey"]}]
    )
    return receipt, {issuer: {KEY_ID: keys["publicKey"]}}, action


def _resolver(pinned: dict):
    return lambda signer, key_id, _issued_at: pinned.get(signer, {}).get(key_id)


def _verify(receipt: dict, pinned: dict, action: dict | None, **overrides) -> dict:
    kwargs = dict(
        resolve_key=_resolver(pinned),
        reference_time=REFERENCE,
        max_age_seconds=MAX_AGE,
        expected_subject_agent=AGENT,
        expected_delegation_ref=DELEGATION_REF,
        action=action,
    )
    kwargs.update(overrides)
    return verify_aps_action_receipt(receipt, **kwargs)


def _fixture(name: str) -> dict:
    return json.loads((FIXTURE_DIR / name).read_text())


# Committed fixture


def test_fixture_is_the_committed_bytes() -> None:
    digest = hashlib.sha256((FIXTURE_DIR / "receipt.json").read_bytes()).hexdigest()
    assert digest == FIXTURE_RECEIPT_SHA256


def test_committed_fixture_verifies_at_its_reference_time() -> None:
    meta = _fixture("meta.json")
    result = verify_aps_action_receipt(
        _fixture("receipt.json"),
        resolve_key=_resolver(_fixture("keys.json")["pinned"]),
        reference_time=datetime.fromisoformat(meta["reference_time"].replace("Z", "+00:00")),
        max_age_seconds=meta["max_age_seconds"],
        expected_subject_agent=meta["expected_subject_agent"],
        expected_delegation_ref=meta["expected_delegation_ref"],
        action=_fixture("action.json"),
    )
    assert result["status"] == VERIFIED
    assert all(result["checks"][name] == PASS for name in CHECKS)
    assert result["reasons"] == []
    assert result["receipt_type"] == ACTION_INTENT_RECEIPT_TYPE
    assert result["core_status"] == "valid"
    assert result["other_signatures"] == "none"


