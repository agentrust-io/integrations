def test_an_appended_non_required_signature_cannot_move_the_result() -> None:
    # Signatures sit outside the receipt_id preimage, so a third party can
    # append a descriptor to a published receipt without changing its
    # identifier. Letting that put a failure reason on a verified result would
    # hand this module's output to that third party.
    receipt, pinned, action = _mint()
    appended = copy.deepcopy(receipt)
    appended["signatures"].append(
        {"alg": "Ed25519", "key_id": "zz", "signer": "did:aps:test:zz-observer", "value": "ab" * 64}
    )
    result = _verify(appended, pinned, action)
    assert result["status"] == VERIFIED
    assert result["checks"]["signature"] == PASS
    assert result["reasons"] == []
    assert result["other_signatures"] == "not_all_verified"
    assert result["checks"]["receipt_id"] == PASS


# Precedence and the translation guard


def test_invalid_wins_over_unverified_when_both_apply() -> None:
    # An unresolved required signer alone is unverified. A wrapper side failure
    # alongside it makes the result invalid, and both reasons stay visible.
    receipt, _pinned, action = _mint()
    result = _verify(
        receipt,
        {},
        action,
        reference_time=ISSUED_AT + timedelta(seconds=MAX_AGE + 1),
    )
    assert result["status"] == INVALID
    assert result["checks"]["signature"] == NOT_CHECKED
    assert result["checks"]["freshness"] == FAIL
    assert f"signature:{AGENT}:{KEY_ID}:key_unresolved" in result["reasons"]
    assert "stale" in result["reasons"]


def test_an_unmapped_core_invalid_state_cannot_read_as_verified(monkeypatch) -> None:
    # Synthetic. Unreachable through this wrapper on 4.0.0, where every invalid
    # state the SDK reports arrives on an axis the translation maps. It exists
    # so a future SDK state cannot silently pass, and it is the one case where
    # no entry in `checks` carries the result.
    receipt, pinned, action = _mint()
    import aps_action_receipt as module

    real = module.verify_receipt_v1

    def unmapped(*args, **kwargs):
        core = dict(real(*args, **kwargs))
        core["status"] = "invalid"
        core["errors"] = ["some_future_code"]
        return core

    monkeypatch.setattr(module, "verify_receipt_v1", unmapped)
    result = _verify(receipt, pinned, action)
    assert result["status"] == INVALID
    assert not any(state == FAIL for state in result["checks"].values())
    assert result["reasons"] == ["unmapped_core_invalid:some_future_code"]


